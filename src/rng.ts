// Свой генератор случайных чисел вместо Math.random.
//
// Зачем. Партию нельзя воспроизвести, если случайность берётся у браузера:
// увидел странное — и показать его больше некому. С сидом достаточно назвать
// число, и та же партия разворачивается заново у кого угодно, включая стенд.
//
// Это же требование записано в журнале под будущий переезд на движок (п. 9):
// ЯДРО НЕ ЗНАЕТ ПРО ДВИЖОК, и глобальный генератор движка убил бы и
// воспроизводимость, и параллельные прогоны. Так что генератор здесь появился
// не ради удобства отладки, а потому что он всё равно был нужен.
//
// Алгоритм — линейный конгруэнтный, тот же, что стенд подсовывал раньше:
// множитель и приращение из Numerical Recipes. Он не криптографический и не
// претендует: нужна повторяемость и ровное распределение, а не стойкость.

let state = 1;
let current = 1;

/** Начать поток заново с этого числа. Возвращает сид, чтобы его было где взять. */
export function setSeed(n: number): number {
  current = n >>> 0;
  state = current;
  return current;
}

/** Сид текущей партии — то, что показывается в панели. */
export function seedOf(): number { return current; }

/** Придумать новый сид: этим начинается партия, которую никто не заказывал. */
export function freshSeed(): number {
  return ((Date.now() >>> 0) ^ ((Math.random() * 4294967296) >>> 0)) >>> 0;
}

/** Следующее число в [0, 1). Замена Math.random() по всему ядру. */
export function rnd(): number {
  state = (state * 1664525 + 1013904223) >>> 0;
  return state / 4294967296;
}

// ---- поток целиком ----------------------------------------------------
// Сид — это НАЧАЛО потока, а не его место. Партия, снятая на двухсотом году,
// развернётся из сида заново только вместе с тем, сколько чисел уже взято;
// хранить счётчик обращений было бы дороже и хрупче, чем само положение.
// Поэтому сохранение уносит обе величины, и продолженная партия идёт ровно
// тем же чередом, что и не прерванная (см. save.ts).
export function rngAt(): number { return state; }
export function setRng(seed: number, at: number): void { current = seed >>> 0; state = at >>> 0; }
