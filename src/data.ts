export const ENGKEYS = ["eng1", "eng2", "eng3", "eng4"];
export function isEngine(k: string): boolean{ return ENGKEYS.indexOf(k) >= 0; }
/** Множитель скорости той модели, что стоит на корабле. Двигателя нет —
 *  единица: корабль всё равно должен куда-то долететь, а не встать намертво. */
export function engMult(parts: { k: string }[]): number {
  let best = 1;
  (parts || []).forEach((p) => { const c = compOf(p.k); if (c && c.mult) best = Math.max(best, c.mult); });
  return best;
}
export function compOf(k: string): Comp{ for (let i=0;i<COMPS.length;i++) if (COMPS[i].key===k) return COMPS[i]; }

// ---- корпус: ступени и места ------------------------------------------
/** Ступени корпуса, от тесной к просторной. */
export const HULLKEYS = ["hull1", "hull2", "hull3", "hull4", "hull5"];
export function isHull(k: string): boolean{ return HULLKEYS.indexOf(k) >= 0; }
/** Сколько мест у этой ступени; 0 — это не корпус. */
export function roomOfKey(k: string): number { const c = compOf(k); return (c && c.slots) || 0; }
/** Корпус, который стоит на корабле: ключ или null. Второго корпуса у корабля
 *  быть не может — он и есть сам корабль. */
export function hullOf(parts: { k: string }[]): string | null {
  let out: string = null;
  (parts || []).forEach((p) => { if (isHull(p.k)) out = p.k; });
  return out;
}
/** Вместимость корабля с такими деталями: сколько ВСЕГО деталей он держит,
 *  считая сам корпус. Корпуса нет (старое сохранение, обломки) — считаем по
 *  тому, что на корабле уже стоит: меньше, чем есть, вместить нельзя. */
export function roomOf(parts: { k: string }[]): number {
  const h = hullOf(parts);
  return h ? roomOfKey(h) : (parts || []).length;
}
/** Сколько мест занимает набор деталей. */
export function sizeOfNeed(need: Record<string, number>): number {
  return Object.keys(need).reduce((a, k) => { return a + need[k]; }, 0);
}
/** Самая тесная ступень, в которую влезает n деталей И которую в галактике
 *  хоть кто-то умеет делать; null — такой нет.
 *
 *  Именно САМАЯ ТЕСНАЯ, а не лучшая: корпус — самая дорогая деталь корабля,
 *  и возить еду в пустом трюме линкора никто не станет. Лестница идёт через
 *  одно (3, 5, 7...), поэтому свободное место у подходящей ступени чаще всего
 *  ровно одно — его и добирает транспорт (shipNeed). */
export function hullFor(n: number): string | null {
  for (let i = 0; i < HULLKEYS.length; i++) {
    const k = HULLKEYS[i];
    if (roomOfKey(k) >= n && corps.some((c) => { return canBuild(c, k); })) return k;
  }
  return null;
}
/** Лучшая ступень корпуса, какую в галактике умеют делать; 0 — никакой. */
export function bestHullMade(): number {
  let best = 0;
  HULLKEYS.forEach((k) => { if (corps.some((c) => { return canBuild(c, k); })) best = Math.max(best, roomOfKey(k)); });
  return best;
}

