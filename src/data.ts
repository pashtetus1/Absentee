/** Чем транспорт добирает свободные места корпуса. Грузовик — трюмами,
 *  переселенческий — жизнеобеспечением: у обоих место прямо переводится в
 *  груз. Платформе, колонии и портальному добирать нечем — у них рецепт, а не
 *  грузоподъёмность, и лишнее место остаётся пустым. */
function fillerOf(vt: VType): string | null {
  return vt.key === "cargo" ? "hold" : vt.key === "liner" ? "life" : null;
}

/** Полный набор деталей корабля: таблица + модель ходового + то, что требует
 *  дорога (под движками межзвёздный рейс везёт ещё и прыжковый) + корпус, в
 *  который всё это влезает.
 *
 *  Корпус берётся САМЫЙ ТЕСНЫЙ из подходящих: он дороже всего остального
 *  вместе взятого, и возить еду в полупустом просторном корпусе никто не
 *  станет. Место, оставшееся свободным (лестница идёт через одно, и у
 *  подходящей ступени чаще всего остаётся ровно одно), транспорт добирает
 *  профильной деталью — оттого межзвёздный грузовик и возит вдвое больше
 *  местного: под движками ему нужен четвёртый угол под прыжковый, значит
 *  корпус Mk2, значит и пятое место, и оно уходит под второй трюм.
 *
 *  null означает, что корабля не будет вовсе: двигателя достать негде, марку
 *  никто не делает или нет корпуса, в который набор влезает. */
export function shipNeed(vt: VType, eng: string | null,
                         extra?: Record<string, number>): Record<string, number> | null {
  if (!eng) return null;
  const n: Record<string, number> = { ...vt.need };
  n[eng] = (n[eng] || 0) + 1;
  // портальный корабль везёт ворота: набор лучшей марки, какую в галактике
  // вообще делают; никто не делает — корабля не будет
  if (vt.key === "gate") {
    const mk = bestMarkMade();
    if (!mk) return null;
    n[mk] = (n[mk] || 0) + 1;
  }
  if (extra) Object.keys(extra).forEach((k) => { n[k] = (n[k] || 0) + extra[k]; });
  // сам корпус занимает место, поэтому в лестнице ищется ступень на деталь
  // больше, чем их набралось
  const room = sizeOfNeed(n) + 1;
  const hk = hullFor(room);
  if (!hk) return null;
  n[hk] = 1;
  const fk = fillerOf(vt), free = roomOfKey(hk) - room;
  if (fk && free > 0) n[fk] = (n[fk] || 0) + free;
  return n;
}

// Способ межзвёздного перемещения выпадает партии ОДИН и случайно. Это не
// ветка развития, а условие задачи: два способа дают две разные логистики,
// и то, что в одном государстве открывается только один, делает партии
// непохожими сильнее, чем любая настройка ползунков.
//   drives — двигатель стоит на каждом корабле. Дёшево начать, платишь вечно:
//            каждый межзвёздный рейс, включая хлебовоз, везёт двигатель.
//   gates  — портальный корабль долетает до соседней звезды и ставит ворота
//            НА ЭТОТ МАРШРУТ. Дорого за каждый маршрут, зато потом по нему
//            летает кто угодно без двигателя — но топливо створ всё равно
//            жжёт, и по одному баку на каждые ворота в пути.
//
// Третьего способа — порталооткрывателей, прожигавших постоянный проход, —
// больше нет: ворота на маршруте делают ровно то же самое, только их видно.
