// ===================== рынок труда на каждом мире =====================

import { btype } from "./data";
import { SCRAP_MAX, SCRAP_MIN, SCRAP_SHARE, YARD_MAX, YARD_MIN, YARD_SHARE } from "./shipyard";
import { corps } from "./state";
import { devCap, devMult } from "./tech";
import { clamp } from "./util";
import { popOf, reserveOf } from "./world";
import type { Pop, Wage, World } from "./types";

export const PULL = 0.03;      // на сколько в месяц цена еды тянется к резерву (при пустом складе)
export const CUT = 0.12;       // сколько казна оставляет себе с хлеба при полном амбаре
// Свободный мир оставляет себе ВТРОЕ МЕНЬШЕ: отделившееся правительство
// отдаёт фермеру почти всё, что выручило. Это про его СОБСТВЕННЫЙ доход, а не
// про платёж метрополии — казённую долю с хлеба метрополия не видела никогда,
// за границу денег отвечает налог (realm.ts).
//
// Ноль тут стоять НЕ МОЖЕТ, и это видно из разложения заработка казны:
//   gain = eaten*price − grown*buy = price*(eaten − grown) + price*grown*CUT*fill
// Второе слагаемое и есть доля. Убери её — и мир, который кормится сам
// (grown >= total, значит eaten = total), получает price*(total − grown) <= 0,
// то есть УБЫТОК каждый месяц ровно на величину излишка: казна скупает весь
// урожай по полной цене, а продаёт только съеденное. Пол на нуле плюс
// содержание прижали бы кассу к нулю навсегда, и посыпалась бы вся цепочка
// порогов "хватает ли денег": хлебовоз, детали к нему, переселенцы, выкуп
// корабля со стоянки. Отделившийся мир получил бы свой стапель и не смог бы на
// нём ничего заказать.
export const CUT_FREE = 0.05;
export function cutOf(w: World): number { return w.free ? CUT_FREE : CUT; }

export function squeeze(jobs: number, workers: number): number { return clamp(1 + 0.5 * (jobs - workers) / Math.max(1.2, workers), 0.55, 2.2); }

// Сколько мир вырастит В ЭТОМ месяце — единственное место, где это считается.
// Раньше формула жила прямо в labour(), а те, кому урожай был нужен для
// решения, прикидывали его заново и каждый по-своему: foodRun брал фермеров на
// урожайность типа, relief — то же плюс освоение, orders — снова без освоения.
// Три оценки одного числа расходились с настоящим тем сильнее, чем лучше был
// освоен мир, и именно из-за этого освоенные миры записывались в нахлебники.
//
// Урожай разложен на ВЫРАБОТКУ ОДНОГО ФЕРМЕРА и число фермеров, потому что по
// выработке считается ещё и заработок в поле: фермер получает за то, что
// вырастил. Прежние price * 2.4 платили одинаково всюду — фермеру на голой
// планете, где он кормит десятую долю человека, столько же, сколько на
// джунглях, и людей тянуло в заведомо бесплодное поле.
export function yieldPerFarmer(w: World): number {
  return w.type.farm *
         (w.rough > 0 ? 0.55 : 1) *          // разруха первых десяти лет
         (w.blight > 0 ? 0.5 : 1) *          // неурожай
         devMult(w);                          // освоение класса миров
}
// ---- гидропоника -----------------------------------------------------------
// Постройка на планете даёт места, где еда растёт НЕ ИЗ ЗЕМЛИ, и потому её
// выработку не трогает ничто из того, что портит поле: ни разруха, ни неурожай,
// ни освоение класса миров. Это ПОЛ, а не ступень лестницы — освоенный терран от
// теплицы не богатеет, а голая планета перестаёт быть приговором.
//
// С разрухой теплица не спорит сама собой, и оговаривать это не нужно: разруха
// длится 120 месяцев, а ферму даёт только голодомор, то есть ещё 48 месяцев
// голода после неё.
//
// Построек пока одна, и потому места складываются, а выработка берётся лучшая:
// при двух разных теплицах это уже неверно — люди пошли бы в лучшую, пока в ней
// есть места, и лишь потом в худшую. Вторая постройка обязана это переписать.
export function hydroJobs(w: World): number {
  let n = 0;
  w.built.forEach((k) => { const b = btype(k); if (b) n += b.jobs; });
  return n;
}
export function hydroYield(w: World): number {
  let y = 0;
  w.built.forEach((k) => { const b = btype(k); if (b && b.yield > y) y = b.yield; });
  return y;
}
// Строгое «больше» обязательно: там, где земля лучше теплицы, теплица не должна
// ОТНИМАТЬ людей у поля и тем снижать урожай. На терране (2.4) и в джунглях
// (2.6) она не включается вовсе.
export function hydroWorkers(w: World): number {
  return hydroYield(w) > yieldPerFarmer(w) ? Math.min(w.pop.farm, hydroJobs(w)) : 0;
}
export function harvestOf(w: World): number {
  const h = hydroWorkers(w);
  return h * hydroYield(w) + (w.pop.farm - h) * yieldPerFarmer(w);
}

// Сколько вырастил СРЕДНИЙ фермер — и это не украшение, а условие сходимости
// кассы. Ниже мир списывает за урожай grown * buy, а платит людям
// pop.farm * wage.farm; сходятся эти два числа ТОЛЬКО при средней выработке.
// Возьми кто-нибудь предельную (мол, «новый работник даст столько-то») — и
// касса мира разойдётся с зарплатой тихо и навсегда.
// Ноль фермеров — не ноль выработки: иначе мир с теплицей и пустым полем никогда
// бы фермеров не завёл, а wage.farm перестала бы быть числом.
export function yieldAvg(w: World): number {
  if (w.pop.farm > 0.001) return harvestOf(w) / w.pop.farm;
  return Math.max(yieldPerFarmer(w), hydroJobs(w) > 0 ? hydroYield(w) : 0);
}
/** Сколько мест в поле ВСЕГО. У земли их без счёта, у теплицы ровно столько,
 *  сколько в ней стоек: за этим порогом выработка нового работника — ноль. */
export function farmRoom(w: World): number { return w.type.farm > 0 ? 1e9 : hydroJobs(w); }
/** Есть ли на мире куда встать фермеру. */
export function canFarm(w: World): boolean { return w.type.farm > 0 || hydroJobs(w) > 0; }

// Закупочная цена: сколько казна мира платит фермеру за единицу. Полный амбар
// сбивает закуп — зерно некуда девать; пустой поднимает его вплотную к цене
// для едоков, и в голод казна на хлебе не зарабатывает ничего. Разница между
// этой ценой и food.price и есть заработок казны, и она рыночная: её двигает
// предложение (амбар), тогда как продажную цену двигает спрос.
export function buyPrice(w: World): number {
  return w.food.price * (1 - cutOf(w) * clamp(w.food.stock / Math.max(1, reserveOf(w)), 0, 1));
}

export function labour(w: World): void {
  const p = w.pop, total = popOf(w);
  if (total <= 0.02) return;

  if (w.rough > 0) w.rough--;
  const rough = w.rough > 0;
  if (w.blight > 0) w.blight--;
  const grown = harvestOf(w);   // разруха, неурожай, освоение
  const buy = buyPrice(w);      // по амбару ДО еды: в него казна и докупает
  // Съедено — не то же, что нужно: в голодный месяц съедают склад плюс урожай,
  // а не полную потребность. Раньше эта величина терялась (склад просто
  // обрезался по нулю), а теперь на неё выписан счёт.
  const eaten = Math.min(total, w.food.stock + grown);
  w.food.stock += grown - total;
  const hungry = w.food.stock < 0;
  if (hungry) w.food.stock = 0;
  w.food.short = hungry ? w.food.short + 1 : 0;
  // Казна мира скупает у фермеров весь урожай и продаёт съеденное едокам. До
  // этого еда на своём мире доставалась даром, а зарплату в поле не платил
  // никто — она считалась, показывалась и двигала людей, оставаясь при этом
  // ничьим обещанием. Чистый итог маленький и меняет знак: сытый мир копит,
  // мир, набивающий закрома, платит за них, а проедающий запас превращает
  // амбар в деньги — на них и покупается хлебовоз. Пол на нуле обязателен:
  // весь код покупок опирается на то, что gov.cash не бывает отрицательной.
  w.food.gain = eaten * w.food.price - grown * buy;
  w.gov.cash = Math.max(0, w.gov.cash + w.food.gain);
  // Цена еды — память мира о голоде, и до сих пор она помнила только ЭТОТ
  // месяц: есть дефицит — дорожает, нет — дешевеет. Склад в ней не участвовал,
  // и мир проедал резерв молча: на родине люди уходили из поля в цеха при
  // ещё полном амбаре, цена не шевелилась, пока он не опустел, и лишь года
  // через три-четыре голода зарплата в поле догоняла цеховую (родина голодала
  // в каждой партии, первый раз на 2-5 году). Теперь цена тянется к резерву:
  // ниже него дорожает даже в сытый месяц, выше — дешевеет, и люди идут в
  // поле, пока есть что есть, а не когда уже нечего.
  const lack = clamp(1 - w.food.stock / Math.max(1, reserveOf(w)), 0, 1);
  w.food.price = clamp(w.food.price * (1 + 0.04 * (total - grown) / Math.max(1, total) + PULL * lack), 0.2, 6);
  w.wage.farm = canFarm(w) ? yieldAvg(w) * buy : 0;

  let jp = 0, js = 0;
  // верфь с работой в очереди просит людей наравне с цехами
  // Стапель из мусора просит рук вчетверо меньше верфи — отсюда и вся разница
  // между ними: он собирает то же самое, но в разы дольше.
  const yw = w.yard && w.yard.queue.some((b) => b.left > 0);
  const yardJobs = !yw ? 0
                 : w.yard.scrap ? clamp(p.prod * SCRAP_SHARE, SCRAP_MIN, SCRAP_MAX)
                 : clamp(p.prod * YARD_SHARE, YARD_MIN, YARD_MAX);
  jp += yardJobs;
  w.branches.forEach((b) => {
    const c = corps[b.corp], n = Math.max(1, c.branches.length);
    b.jobs.prod = clamp(c.cash / (180 * n), 0.3, 8) * (rough ? 0.35 : 1);   // цехов ещё нет
    b.jobs.sci = clamp(c.cash / (420 * n), 0.1, 5) * (rough ? 0.35 : 1) * (c.native ? 2.2 : 1);   // отделившиеся живут наукой
    jp += b.jobs.prod; js += b.jobs.sci;
  });
  w.wage.prod = 3.0 * squeeze(jp, p.prod);
  w.wage.sci = 4.2 * squeeze(js, p.sci);
  const kp = jp > 0 ? Math.min(1, p.prod / jp) : 0, ks = js > 0 ? Math.min(1, p.sci / js) : 0;
  w.branches.forEach((b) => { b.emp.prod = b.jobs.prod * kp; b.emp.sci = b.jobs.sci * ks; });
  if (w.yard) w.yard.crew = yardJobs * kp;

  const outP = Math.max(0, p.prod - jp) * 0.05, outS = Math.max(0, p.sci - js) * 0.05;
  p.prod -= outP; p.sci -= outS; p.free += outP + outS;

  const openP = Math.max(0, jp - p.prod), openS = Math.max(0, js - p.sci);
  // Готовность занять место — ПОСТОЯННАЯ. Здесь стоял рычаг пособия, и он был
  // ложным выбором: пособие не могло дойти до людей (кошелька у населения нет,
  // см. журнал), зато тормозило наём вот тут и переток в поле ниже, а через
  // безработицу поднимало wantOut и гнало людей с планеты. Ноль был строго
  // лучше любого другого положения, а рычаг, у которого одно положение всегда
  // верное, — не рычаг, а украшение.
  const eager = 0.32;
  const take = Math.min(p.free * eager, openP + openS);
  if (take > 0 && openP + openS > 0) {
    const shareP = openP / (openP + openS);
    p.free -= take; p.prod += take * shareP; p.sci += take * (1 - shareP);
  }
  // «Есть куда встать», а не «мир умеет кормиться». Разница вся в теплице: на
  // газовом гиганте (type.farm = 0) мест ровно столько, сколько в ней стоек, а
  // за порогом выработка НОЛЬ. Без учёта мест ручеёк гнал бы туда людей вечно,
  // они осели бы мёртвым грузом и разбавили среднюю выработку, по которой всем
  // остальным платят.
  const room = farmRoom(w) - p.farm;
  if (canFarm(w) && room > 0) {
    const toFarm = Math.min(p.free * 0.04, room);
    p.free -= toFarm; p.farm += toFarm;
  }

  // Теплицу наполняют ДО заработков, пока в амбаре меньше месячной нормы. Это
  // не рынок труда, а выживание: рынок тут отступает, но ровно на число мест в
  // теплице и ровно пока мир голоден. Берут сперва незанятых, потом из науки и
  // цехов — в том порядке, в каком людей проще увести от менее срочного дела.
  const hungryNow = w.food.stock < total;
  let need = Math.min(Math.min(hydroJobs(w), farmRoom(w)) - p.farm, total * 0.02);
  if (hungryNow && need > 0) {
    (["free","sci","prod"] as (keyof Pop)[]).forEach((k) => {
      if (need <= 0) return;
      const take = Math.min(p[k], need);
      p[k] -= take; p.farm += take; need -= take;
    });
  }

  let best: keyof Wage = canFarm(w) ? "farm" : "prod";
  if (w.wage.prod > w.wage[best]) best = "prod";
  if (w.wage.sci > w.wage[best]) best = "sci";
  let mv = 0;
  (["farm","prod","sci"] as (keyof Wage)[]).forEach((k) => {
    if (k === best) return;
    if (w.wage[best] < w.wage[k] * 1.12) return;
    const open = best === "farm" ? farmRoom(w) - p.farm : (best === "prod" ? jp - p.prod : js - p.sci);
    if (open <= 0) return;
    // Из ГОЛОДНОЙ теплицы не уходят. Мест в ней горстка, и заработком она не
    // берёт никогда: поле платит по своей выработке, а та упирается в потолок
    // цены еды, тогда как лаборатория отделившихся платит вдвое (у них 2.2
    // научных места на филиал — см. выше). Без этого порога мир голодал двести
    // месяцев при ПУСТОЙ теплице, потому что все сидели в науке.
    const floor = (hungry && k === "farm") ? Math.min(hydroJobs(w), p.farm) : 0;
    const m = Math.min(Math.max(0, p[k] - floor) * 0.012, open);
    p[k] -= m; p[best] += m; mv += m;
  });
  w.flow = mv > 0.02 ? "идут в " + ({ farm:"поле", prod:"цеха", sci:"лаборатории" })[best] : "перетока почти нет";

  // Рост и убыль. Тесно — растут медленнее, голодно — убывают. Убыль берётся
  // со ВСЕХ каст: если вычитать только из свободных, итог расходится с
  // суммой по занятиям и панель начинает врать (так уже было).
  // Освоение поднимает предел, но не выше потолка мира, если он назначен: у
  // столицы это 32 человечка (то есть тридцать два миллиарда), и никакая
  // технология не делает из одной планеты две.
  w.cap = Math.min(w.cap0 + devCap(w), w.capTop === undefined ? Infinity : w.capTop);
  const fill = total / w.cap;
  // рост медленный: столица и так почти полна, а колонии должны наполняться
  // десятилетиями, а не за десяток лет
  // Голод должен КУСАТЬСЯ. При прежних 0.25% в месяц за четыре года голода мир
  // терял 11% людей — то есть голодал часто (треть месяцев) и безнаказанно.
  const g = hungry ? -0.004 : 0.0012 * (1 - fill);
  const add = total * g;
  if (add >= 0) p.free += add;
  else (["farm","prod","sci","free"] as (keyof Pop)[]).forEach((k) => { p[k] = Math.max(0, p[k] + add * p[k] / total); });

  // Желание уехать: теснота плюс безработица плюс голод. Это не приказ игрока
  // и не приказ компании — просто людям тут нечего ловить.
  const unemp = p.free / Math.max(0.05, total);
  const push = Math.max(0, fill - 0.7) * 1.4 + Math.max(0, unemp - 0.12) * 1.2 + (hungry ? 0.5 : 0) + (rough ? 0.3 : 0);
  w.wantOut = clamp(push * total * 0.25, 0, p.free + p.farm * 0.3);
  w.wantIn = Math.max(0, w.cap * 0.85 - total);
}

