// Формы предметных объектов.
//
// Это не украшение и не документация: ядро когда-нибудь переедет на C#
// (журнал, п. 9), и здешние интерфейсы — черновик будущих структур /Sim.
// Ровно поэтому они описывают ВЕЩИ мира, а не удобство отрисовки.
//
// Правило раскладки: поле необязательное (со знаком ?) только тогда, когда его
// отсутствие ЗНАЧИМО — верфь без vent строит не предприятие, у рейса без relief
// нет частного благодетеля. Если поле просто дописывается позже, оно всё равно
// обязательное: пусть компилятор требует его завести сразу.

// ---- технологии -------------------------------------------------------
// Всё, во что компания может вкладывать деньги, устроено одинаково: ключ,
// имя и сложность. Отсюда общий Tech и allTech() поверх пяти таблиц.
export interface Tech { key: string; name: string; short: string; diff: number; }

/** Деталь: её производят, продают и возят.
 *
 *  mult есть ТОЛЬКО у ходовых двигателей: их четыре модели, и различаются они
 *  ровно этим числом — во сколько раз быстрее идёт корабль, на котором стоит
 *  такой двигатель. У остальных деталей множителя нет, и его отсутствие
 *  означает «это не двигатель», а не «забыли заполнить». */
export interface Comp extends Tech {
  work: number; base: number; glyph: string;
  mult?: number;                  // ходовой двигатель: множитель скорости внутри системы
  slots?: number;                 // корпус: сколько деталей держит, считая себя
  sight?: number;                 // телескоп: докуда видит спутник с ним
  arm?: Arm;                      // военная деталь: чем бьёт, чем держит, чем высаживает
}

/** Военная деталь. Пять семейств и у каждого пять ступеней:
 *
 *    beam  — энергетическое оружие: чем корабль бьёт в бою;
 *    armor — броня: сколько он держит;
 *    bomb  — бомбы: удар с орбиты по наземному бою внизу;
 *    drop  — десантная капсула: сколько людей корабль высаживает на планету;
 *    gun   — наземное оружие: на корабль НЕ ставится вовсе, им вооружают
 *            ополчение в наземной битве.
 *
 *  power — во что ступень превращается в бою: урон, запас прочности, сила
 *  бомбёжки, число десанта, сила ополчения. Одно поле на все пять семейств
 *  потому, что смысл у него один — «насколько эта ступень сильнее первой», —
 *  а что именно им считают, решает kind. */
export interface Arm { kind: string; lvl: number; power: number; }

/** Чертёж военного корабля: полный состав, который кто-то однажды придумал.
 *
 *  Деталей у корабля может быть какой угодно набор, и заранее его никто не
 *  знает: чертёж РОЖДАЕТСЯ в партии (arms.ts, rollDesign) из того, до чего
 *  галактика доросла, и до него ещё надо доисследоваться. Патент на чертёж
 *  самый обычный: пока он держится, строить по этому чертежу может только
 *  хозяин — остальным остаётся ждать или заказывать у него.
 *
 *  gen — поколение: ноль у «самоделки» вольницы (её не исследуют, её знает
 *  каждый, кто взялся за оружие), дальше по порядку появления. */
export interface Design extends Tech {
  gen: number;
  hull: string;                   // корпус, в который состав уложен
  need: Record<string, number>;   // полный состав, считая корпус и ходовой
  build: number;                  // месяцев сборки, как у VType
}
/** Класс миров: право колонизировать такие планеты. */
export interface ColTech extends Tech {}
/** Марка межзвёздного перехода: чем выше, тем дальше бьёт и тем быстрее идёт
 *  межзвёздный рейс. Марка отвечает за дорогу МЕЖДУ звёздами — и за дальность,
 *  и за скорость; внутри системы её нет вовсе, там правит ходовой двигатель. */
export interface Mark extends Comp { range: number; mark: number; speed: number; }
/** Ходовой двигатель: множитель скорости ВНУТРИ системы. Это деталь (см. Comp
 *  с mult), а не отдельная таблица: моделей четыре, и корабль несёт одну из
 *  них — ту, что на него поставили при сборке. */
export interface Engine extends Tech { mult: number; }
/** Освоение класса миров, Mk1 и до бесконечности. */
export interface Dev extends Tech { cls: string; mark: number; }

/** Тип планеты: предел населения, урожай с фермера, каким классом осваивается. */
export interface PType {
  key: string; name: string; cap: number; farm: number;
  cls: string;                    // класс: по нему идут марки освоения
  tech: string;                   // технология колонизации ЭТОГО типа
  col: string; w: number;
}
/** Класс миров: имя для марок освоения. Правом колонизировать больше не
 *  торгует — оно у каждого типа планеты своё (COLTECH). */
export interface WorldClass { key: string; name: string; short: string; diff: number; }

/** Что можно построить: из каких деталей, сколько месяцев, что даёт. */
export interface VType {
  key: string; name: string; need: Record<string, number>; build: number; glyph: string;
  yield?: number;                 // только у разработки астероидов
  term?: number;                  // на сколько месяцев хватает жилы
}

/** Постройка на планете: что она даёт и скольким людям.
 *
 *  Пара к VType, и разница между ними ровно та, что между кораблём и домом:
 *  корабль строят из деталей и он улетает, постройка стоит на месте и меняет
 *  ПРАВИЛА мира, на котором стоит. Пока постройка одна — гидропонная ферма, —
 *  но таблица заведена таблицей с самого начала: вторая постройка не должна
 *  требовать переделки механики, только новой строки.
 *
 *  jobs — сколько мест она открывает, yield — сколько с одного работника. У
 *  фермы это еда, и она НЕ зависит ни от типа планеты, ни от разрухи, ни от
 *  неурожая, ни от освоения: теплица на то и теплица. */
export interface BType { key: string; name: string; short: string; jobs: number; yield: number; glyph: string; }

/** Способ межзвёздного перемещения. Партии достаётся ОДИН и случайно.
 *
 *  comp — деталь, без которой этот способ не работает: прыжковый двигатель под
 *  движками, портальный набор под воротами. Деталь ЧУЖОГО способа в партии не
 *  нужна вообще, и наука обязана это знать — иначе компании годами вкладываются
 *  в то, что здесь никогда не полетит.
 *
 *  Поля «каким кораблём открывают звезду» здесь БОЛЬШЕ НЕТ: звёзды не
 *  открывают кораблями вовсе, их открывает спутник с телескопом (Sat). Способ
 *  отвечает только за дорогу — как попасть туда, что уже видно. */
export interface Move { key: string; name: string; comp: string; hint: string; }

// ---- галактика --------------------------------------------------------

/** Крупный именованный астероид. taken — уже занят чьей-то разработкой. */
export interface Rock { name: string; r: number; ang: number; s: number; seed: number; taken: boolean; }

/** Место под звёздные ворота. Пока не построены, built ложно. */
/** Ворота стоят НА МАРШРУТЕ, а не в системе: одни на пару звёзд, и в системе
 *  их столько, сколько от неё расходится проложенных маршрутов. Прежние
 *  «ворота в системе» дотягивались сразу до всех других ворот — сеть без
 *  рёбер, где нечего прокладывать и не на что смотреть. */
export interface Gate {
  a: number; b: number;                 // какие системы соединяет
  built: boolean; building: boolean;
  owner: number; born?: string;
  mark: number;                         // марка комплекта: от неё скорость прохода
  upgrading?: boolean;                  // на маршрут уже идёт комплект старшей марки
  trips: number;                        // недавний трафик, рейсов с затуханием (~5 лет)
}

/** Планета. Пока не колонизирована, world пуст — миром она не является.
 *
 *  Названа Planet, а не Body, хотя поле в системе зовётся bodies: Body есть в
 *  стандартной библиотеке браузера (тело HTTP-ответа), и в файле без импорта
 *  тип молча разрешался в НЕЁ. Ошибка при этом всплывала где-то далеко и
 *  выглядела бессмысленно.
 */
export interface Planet {
  name: string; type: PType; r: number; ang: number; rad: number;
  kind: string; sys: number; world: World | null;
  claimed?: boolean;              // кто-то уже везёт сюда колониальный модуль
}

/** Класс звезды — её цвет, как в Master of Orion 2: голубые, белые, жёлтые,
 *  оранжевые, красные и коричневые. Пока это только облик: на планеты и на
 *  что-либо в партии класс не влияет. */
export interface StarClass {
  key: string; name: string;      // name — прилагательным: «красная звезда»
  core: string;                   // ядро: почти белое, с отливом своего цвета
  rgb: string;                    // цвет короны "r,g,b" — для прозрачных градиентов
  size: number;                   // во сколько раз светило крупнее жёлтого в виде системы
  share: number;                  // доля таких звёзд в галактике
}

export interface Sys {
  id: number; name: string; x: number; y: number;
  unlocked: boolean;              // звезду разглядели в телескоп: видно, что в ней
  depth: number;                  // удалённость от родины, "переход N"
  pulse: number;
  bodies: Planet[]; rocks: Rock[]; ventures: Venture[];
  ships: Ship[]; stations: Station[]; sats: Sat[];
  mines: number;
  belt: boolean;                  // есть ли пояс астероидов
  gateR: number;                  // радиус последней орбиты — на ней стоят створы
  gateAngs: Record<number, number>; // место под створ к каждому возможному соседу (в пределах 30° от луча)
  portals: Portal[];              // построенные створы; один створ ведёт ко всем звёздам в своём конусе
}

/** Створ — сооружение на последней орбите. Смотрит в свою сторону и ведёт ко
 *  всем звёздам в конусе ±40° от неё, до которых достаёт его марка. Маршрут
 *  (Gate) открыт, когда створы на обоих концах смотрят друг на друга. */
export interface Portal { ang: number; mark: number; owner: number; born?: string; }

// ---- мир --------------------------------------------------------------

export interface Pop { farm: number; prod: number; sci: number; free: number; }
export interface Wage { farm: number; prod: number; sci: number; }
export interface Food {
  stock: number; price: number; short: number;
  /** Что казна мира получила с хлеба в ПРОШЕДШЕМ месяце: продала едокам минус
   *  закупила у фермеров. Считается в labour() по складу ДО еды, поэтому
   *  панель не может восстановить это число сама — только соврать. */
  gain: number;
}

/** Филиал компании на мире: её люди и её рабочие места здесь. */
export interface Branch {
  corp: number; world: World;
  emp: { prod: number; sci: number };
  jobs: { prod: number; sci: number };
  wip?: Record<string, number>;   // что цех сейчас делает
}

/** Населённая планета: люди, еда, кошелёк правительства, места под филиалы. */
export interface World {
  body: Planet; sys: number; type: PType;
  cap: number; cap0: number;
  capTop?: number;                // жёсткий потолок: выше него не поднимает даже освоение
  pop: Pop; wage: Wage; food: Food;
  gov: { cash: number };
  slots: number;
  rights: number[];                // номера компаний, получивших право на филиал
  branches: Branch[];
  wantOut: number; wantIn: number;
  founder: number;                // кто основал; -1 у родины
  born: string;
  parts: Part[];                  // из чего был собран колониальный модуль
  flow: string; blight: number;
  rough: number;                  // месяцы разрухи: свежая колония живёт на привозном
  yard?: Shipyard;                // верфь у планеты, если построена
  yardTries?: number;             // сколько раз предлагали верфь здесь
  yardRetryAt?: number;           // раньше этого месяца не предложат снова
  edge?: boolean;                 // планета дошла до края, жребий уже брошен
  /** Заложенный после голодомора стапель: когда встанет и чей будет. Знак «?»
   *  тут значим — его отсутствие и есть «ничего не строится». */
  edgeYard?: { at: number; owner: number };
  free?: boolean;                 // мир объявил независимость и вышел из государства
  reliefAt?: number;              // когда сюда в последний раз слали помощь
  /** Уровень наземного оружия в арсенале мира: 0 — арсенала нет. Его покупает
   *  генерал на военный бюджет (army.ts), и он же расходуется в наземной
   *  битве. Не «сколько стволов», а КАКИЕ: ополчение вооружается тем, что
   *  лежит, и после боя арсенал пуст. */
  arms: number;
  /** Наземная битва, которая идёт на этой планете прямо сейчас. Отсутствие
   *  значимо: боя нет. */
  war?: Ground;
  /** Что на мире построено, ключами из BTYPES. Без знака «?»: пустой список и
   *  отсутствующий значат одно и то же, а рядом уже лежат rights и parts. */
  built: string[];
}

// ---- компании ---------------------------------------------------------

export interface Corp {
  id: number; name: string; color: string;
  craft: string;                         // ремесло словом: «буры», «самолёты», «разбой»
  nerve: number;                         // смелость: во сколько раз просит выше ходовой
  apt: Record<string, number>;           // склонность к каждой технологии
  cash: number;
  known: Record<string, boolean>;        // что уже освоено
  /** Карты систем: какие звёзды контора знает. Знание ЧАСТНОЕ — своим спутником
   *  или купленной картой (charts.ts); государство видит систему, только когда
   *  её знают трое. Ключ — номер системы. */
  maps: Record<number, boolean>;
  spent: Record<string, number>;         // сколько вложено в каждую технологию
  stock: Record<string, Record<string, number>>;   // склад с адресом: система -> деталь
  tot?: Record<string, number>;          // сумма склада, держится вместе с ним
  target: string | null;                 // во что вкладывается сейчас
  order: Order | null;                   // что заказано на постройку
  branches: Branch[];
  sold: number; bought: number; cool: number;
  embargo: Record<string, number>;       // кому и в чём отказано
  ask: Record<string, number>;           // во сколько раз просит выше ходовой цены
  pirate?: boolean;                      // ушла в разбой
  crest?: number;                        // номер гербовой фигуры; есть ТОЛЬКО у государства
  home?: World;                          // логово вольницы
  needYard?: boolean;                    // хотела заказать, но собрать негде — повод предлагать верфь
  origin?: string;                       // какой жребий её породил
  bornAt?: World;                        // мир, на котором она возникла
  native?: string;                       // класс миров, родной отделившейся колонии
  fuelAcct?: Record<number, { fly: Record<string, number> }>;   // топливо в пути, по системам
}

// ---- заказы и стройки -------------------------------------------------

/** Заказ компании: свезти детали и построить. */
export interface Order {
  type: string; need: Record<string, number>; got: Record<string, number>;
  parts: Part[]; born: string;
  wait?: number;                  // месяцев ждём недостающую деталь
  fly?: Record<string, number>;   // чего уже везут, чтобы не заказать дважды
  sys?: number;                   // где собирают (система верфи; детали едут сюда)
  yard?: Shipyard;                // на какой именно верфи: в системе их может быть несколько
  dst?: number;                   // куда полетит готовое
  to?: number;                    // цель прыжка
  from?: number;                  // точка старта прыжка: система с заселённой планетой
  rock?: Rock;                    // какой астероид разрабатывать
  upgrade?: boolean;              // портальный: не новый маршрут, а переделка ворот на старшую марку
}

/** Счёт того, что уже везут: чтобы не заказать одно и то же дважды.
 *  Есть и у заказа, и у подписки, и у топливного счёта компании. */
export interface FlyAcct { fly?: Record<string, number>; }

/** Кому достанется купленная деталь, когда грузовик её довезёт: в заказ, в
 *  подписку на колонию, в одобренную верфь или просто на склад покупателя
 *  (так возят топливо). Это ЗАПИСЬ, а не замыкание, и ровно поэтому:
 *  замыкание нельзя уложить в сохранение, а рейс с деталью — часть партии,
 *  как и всё остальное, что летит. Сама выдача собрана в одном месте, в
 *  market.ts; здесь только адрес. Кому именно — говорит acct того же рейса:
 *  это и есть тот самый заказ, подписка или предложение.
 */
export type Consign = "stock" | "order" | "project" | "proposal";
/** Купленная деталь на пути к покупателю: лежит на погрузке (freight) или уже
 *  в трюме. Чья (owner), что (k), кем сделана (from), откуда (sys) и куда (dest),
 *  кому достанется (consign) и в чей счёт летит (acct). at — месяц покупки. */
export interface Lot { owner: number; k: string; from: number; sys: number; dest: number; consign: Consign; acct: FlyAcct; at: number; }

/** Одна купленная деталь: что (k), у кого (from), почём. */
export interface Part { k: string; from: number; price?: number; sys?: number; }

/** Подписка на колонию: скидываются несколько компаний. */
export interface Project {
  lead: number; body: Planet; dst: number; sys: number;
  yard?: Shipyard;                // где собирают модуль
  cost: number; purse: number;
  need: Record<string, number>; got: Record<string, number>; parts: Part[];
  backers: { corp: number; sum: number }[];
  age: number; born: string;
  done?: boolean;
  wait?: number;                  // месяцев ждём недостающую деталь
  fly?: Record<string, number>;   // чего уже везут
  seen?: number; seenPurse?: number;      // на чём подписка стояла в прошлый раз
}

// ---- то, что летает и работает ----------------------------------------

/** Куда направляется корабль: астероид, планета, орбита спутника. Общее у
 *  всех трёх — место в системе (ang, r), и ровно им пользуется отрисовка. */
export interface Dest { kind: string; ref: Rock | Planet | Sat; label: string; }

/** Спутник: не корабль, а СООРУЖЕНИЕ на орбите. Состав деталей у него один —
 *  телескоп, и телескоп делает единственное, ради чего спутник нужен:
 *  ищет закрытые звёзды вокруг своей системы. Ступеней телескопа четыре, и
 *  дальность у ступени та же, что у марки перехода того же номера: куда
 *  долетаешь, туда и видишь. Находит он их ПО ОДНОЙ и годами.
 *  Вторым может стоять боевой лазер — может, а не обязан: пока он не делает
 *  ничего, бои идут отдельной веткой, и спутник с ним отличается только ценой
 *  и видом. Когда бои придут, вооружённые спутники уже будут стоять там, где
 *  компании решили их поставить.
 *
 *  live/building — как у Venture: спутник числится в системе с того месяца,
 *  как его заложили, чтобы второй туда не полетел, а работать начинает, когда
 *  встанет на орбиту. found — сколько звёзд он открыл, встав. */
export interface Sat {
  sys: number; owner: number; color: string;
  /** Вокруг чего кружит телескоп. Спутник не висит приклеенным к точке возле
   *  планеты, как было: он ОБХОДИТ её, как стоянка и верфь, — тем и отличается
   *  сооружение на орбите от значка на карте. Пусто — планет в системе нет
   *  вовсе, и кружить остаётся вокруг самого светила. */
  body?: Planet;
  orb: number;                          // радиус орбиты от центра того, что обходит
  ang: number;                          // где на этой орбите он начал: фаза
  parts: Part[]; born: string;
  mark: number;                         // ступень телескопа, 1..4
  range: number;                        // докуда видит: дальность своей ступени
  /** Запас прочности, как у военного корабля (shipHp по его же деталям).
   *  Держится МЕЖДУ боями: спутник не чинится сам, и вторая стычка застаёт его
   *  таким, каким его оставила первая. */
  hp: number;
  /** На борту энергетическое оружие (семейство beam, arms.ts). Своего «лазера»
   *  у спутника больше нет: пока бои шли другой веткой, он был отдельной
   *  деталью, теперь ветки сошлись и оружие в игре одно. */
  armed: boolean;
  live: boolean; building: boolean;
  /** Месяцев всматривается в очередную звезду. Спутник находит их ПО ОДНОЙ и
   *  не сразу (SCAN_MONTHS в charts.ts): небо большое, а телескоп один. */
  scan: number;
  found: number;                        // сколько звёзд нашёл за свою жизнь
}

/** Платформа, вставшая на астероид: видимый след предприятия в системе. */
export interface Station {
  dest: Dest; color: string; glyph: string; size: number; vent: Venture; ang: number;
}

/** Разработка астероидов: жила, из которой капает доход, пока не кончится. */
export interface Venture {
  sys: number; lead: number; type: string; name: string; parts: Part[];
  left: number; yield: number; born: string; dest: Dest;
  live: boolean; building: boolean;
}

/** Верфь: детали свезены, идёт сборка. */
export interface Yard {
  vt: VType; lead: number; color: string; glyph: string;
  parts: Part[]; left: number; total: number;
  vent?: Venture; dest?: Dest; dst?: number;
  sat?: Sat;                      // спутник: что именно собирают и куда оно встанет
  to?: number; fuelWait?: number;
  forWorld?: World;               // транспорт: чьей планете он достанется
  forCorp?: number;               // транспорт: чьей компании (иначе государственный)
  from?: number;                  // прыжок: откуда стартовать; не система верфи, если её нет в дальности
  body?: Planet; backers?: { corp: number; sum: number }[];
  upgrade?: boolean;              // портальный: переделка существующих ворот
  des?: string;                   // военный: по какому чертежу собирают
  role?: string;                  // военный: кем он станет, сойдя со стапеля
}

/** Как государство отвечает на предложения. В браузере manual — решает игрок;
 *  остальное — для стенда, иначе партия без игрока встала бы на первом же
 *  предложении. random берёт монетку из своего генератора: воспроизводимо. */
export type ApproveMode = "manual" | "always" | "never" | "random";

/** Верфь: постройка у планеты. Строит по очереди, тем быстрее, чем больше рук. */
export interface Shipyard {
  id: number; world: World;
  owner: number;                  // -1 государственная, пользуются все; иначе — хозяин
  ang: number;                    // орбита вокруг своей планеты
  queue: Build[];                 // кто первый встал
  crew: number;                   // сколько людей удалось нанять в этом месяце
  born: number;
  backers: { corp: number; sum: number }[];   // кто скидывался на постройку
  /** Стапель из мусора: не верфь, а её урезанная версия, собранная своими
   *  руками после голодомора. Строит всё то же самое, но берёт вчетверо меньше
   *  рук и оттого идёт в разы дольше. Хозяин может доложить денег и довести её
   *  до настоящей — тогда признак снимается. Отсутствие значимо: это верфь. */
  scrap?: boolean;
}

/** Позиция очереди верфи. Пока это Yard; шаг 3 плана уводит Sys.yards сюда. */
export type Build = Yard;

/** Предложение компаний построить верфь. Первое место, где решает игрок. */
export interface Proposal {
  id: number; world: World; lead: number;
  cost: number;                   // деньгами
  purse: number;                  // сколько внесли компании
  share: number;                  // их доля, не выше SHARE_CAP
  stateSum: number;               // сколько доложила казна
  need: Record<string, number>; got: Record<string, number>; parts: Part[];   // детали, как у Project
  fly?: Record<string, number>;   // что уже везут
  backers: { corp: number; sum: number }[];
  state: "pending" | "approved" | "declined" | "building" | "done";
  since: number; until: number;   // подано; до какого месяца висит
  attempt: number;                // которая попытка для этой планеты
  left: number;                   // сколько осталось строить
}

/** Корабль внутри системы: идёт от верфи к цели. */
export interface Ship {
  kind: string; corp: number; color: string; glyph: string; size: number;
  t: number; dur: number; tp?: number;
  trail: { x: number; y: number }[];
  x: number; y: number; ang: number;
  born: string; captain: string;
  parts: Part[];
  yard?: Shipyard;                // с какой верфи сошёл: оттуда и стартует
  dest?: Dest; vent?: Venture; sat?: Sat;
  body?: Planet; backers?: { corp: number; sum: number }[];
}

// ---- война ------------------------------------------------------------
// Военный корабль НЕ ходит рейсами и ничего не возит: он стоит там, где
// поставлен, и ждёт повода. Оттого он и не Ship и не Voyage — у тех вся суть в
// том, что они идут из точки в точку и приходят.

/** Военный корабль: собран по чертежу, стоит в системе, ждёт боя.
 *
 *  role — зачем он здесь и есть ровно три ответа: "raid" (вольница вышла на
 *  промысел), "guard" (компания стережёт свои рейсы), "police" (казённый,
 *  куплен на военный бюджет). Разница между ними не в силе, а в том, за кого
 *  он вступится. */
export interface Warship {
  id: number; owner: number;      // контора; -1 — государственный
  des: string;                    // ключ чертежа, по которому собран
  parts: Part[];
  sys: number;                    // где стоит
  hp: number; hpMax: number;
  dmg: number;                    // урон в месяц боя
  role: string;
  ang: number;                    // орбита, чтобы было видно на сцене
  captain: string; born: string;
  fight?: number;                 // номер боя, в котором он занят
}

/** Боец в космическом бою: военный корабль, вооружённый СПУТНИК или сам
 *  мирный, за которым пришли. У мирного нет ни урона, ни ссылки на корабль —
 *  он тут жертва, а не участник, и именно это отсутствие значимо. Спутник —
 *  участник неподвижный: он не догоняет и не отступает, он просто стоит в
 *  своей системе и стреляет по тем, кто затеял бойню у него под носом. */
export interface Fighter {
  owner: number; name: string; color: string;
  hp: number; hpMax: number; dmg: number;
  parts: Part[];
  ship?: Warship;                 // военный корабль, если это он
  sat?: Sat;                      // спутник: стреляет с орбиты и никуда не уходит
  prey?: boolean;                 // сам мирный корабль
}

/** Космический бой. Идёт месяцами и виден на карте: за него можно ткнуть и
 *  смотреть, чем кончится. */
export interface Fight {
  id: number; sys: number;        // ближайшая звезда — ею бой и подписан
  x: number; y: number;           // место на карте галактики
  att: Fighter[]; def: Fighter[];
  raider: number;                 // чья вольница напала
  prey?: Voyage;                  // рейс, который держат; нет — бьются сами по себе
  left: number; total: number;
  log: string[];
  done?: string;                  // "att" — взяли, "def" — отбились
}

/** Наземная битва на планете: восставшие против ополчения корпораций.
 *
 *  Считается людьми и оружием, а показывается схемой (render/war.ts): планета,
 *  фермы, цеха и лаборатории, и видно, чья сейчас каждая клетка. Восставших
 *  ВСЕГДА больше — они и есть население; корпорации берут выучкой и тем, что
 *  лежит в арсенале, купленном на военный бюджет. */
export interface Ground {
  world: World;
  corp: number;                   // контора восставших
  kind: string;                   // какой жребий выпал: "вольница" или "государство"
  reb: { men: number; men0: number; arms: number };
  gov: { men: number; men0: number; arms: number };
  left: number; total: number;
  tiles: { k: string; side: number }[];   // клетки планеты: 0 — за корпорации, 1 — за восставших
  log: string[];
  done?: string;                  // "reb" — восстание победило, "gov" — подавлено
}

/** Прыжковый корабль у точки старта: ждёт межзвёздного топлива, потом прыгает. */
export interface Staged {
  kind: string; corp: number; color: string; parts: Part[];
  at: number;                     // где стоит
  to: number;                     // куда прыгнет
  fuelWait: number; captain: string; born: string;
  upgrade?: boolean;
}

/** Рейс между звёздами или между мирами.
 *
 *  Форм две, и они правда разные. Хлебовоз и переселенческий идут МЕЖДУ МИРАМИ:
 *  from и to — миры, есть qty и captain. Рейс с деталью идёт МЕЖДУ СИСТЕМАМИ:
 *  вместо from стоит sysFrom, to — номер системы, k — что везут, take — что
 *  сделать по прибытии. Разводить это в два типа значило бы разводить и весь
 *  код движения, который относится к ним одинаково: летит, долетел, перехватили.
 */
export interface Voyage {
  kind: string;
  // ЕДИНСТВЕННОЕ оставшееся any в ядре, и оно намеренное. Здесь лежит либо мир,
  // либо номер системы — смотря какой это рейс. Написать "World | number"
  // недорого, но тогда двадцать два места в коде движения обрастут
  // приведениями, а приведение не проверяет, оно только переносит допущение.
  // Настоящее решение — разбить Voyage на два типа с разбором по kind, и код
  // движения к этому уже готов: он почти везде и так ветвится по kind.
  // Это отдельная работа, а не побочный эффект типизации.
  to: any;
  qty?: number;                   // сколько везёт; у парома и прыжка груза нет
  parts?: Part[];                 // груз деталей; у рейса с ОДНОЙ деталью его нет
  color: string; t: number; dur: number; tp?: number;
  born?: string; captain?: string;
  from?: any;                     // мир отправления (у рейсов между мирами)
  sysFrom?: number;               // система отправления (у рейсов с деталью)
  k?: string;                     // какая деталь
  corp?: number;                  // чей корабль
  forCorp?: number;               // для кого везут
  shipOwner?: number;             // чей сам грузовик (у рейса с деталью — покупателя)
  acct?: FlyAcct;
  consign?: Consign;              // кому достанется деталь, когда долетит
  relief?: number;                // чья частная помощь; иначе везёт правительство
  cargo?: string;                 // что за груз у платформы или модуля
  jumpTo?: number;                // паром везёт прыжковый к точке старта: куда прыгать оттуда
  upgrade?: boolean;              // портальный идёт переделывать ворота, а не прокладывать маршрут
  /** Порожний перегон (kind "empty"): за чем корабль идёт. Груз уже оплачен и
   *  отложен у погрузки; по прилёте уходит рейсом этого вида (fleet.ts). */
  next?: { kind: string; from: World; to: any; qty: number; relief?: number; lots?: Lot[]; forCorp?: number };
  /** Детали в трюме грузовика (kind "parts"). У рейсов из старых сохранений их
   *  нет — там одна деталь в k, consign и acct (freight.ts, lotsOf). */
  lots?: Lot[];
  dest?: Dest; vent?: Venture; sat?: Sat; body?: Planet;
  backers?: { corp: number; sum: number }[];
  /** Номер боя, в котором рейс задержан. Пока он стоит, рейс НЕ движется: его
   *  держат на прицеле, и весь спор о том, дойдёт ли он вообще. */
  fight?: number;
}

/** Отработанный транспортник на орбите: его перекупят под следующий рейс. */
export interface Dock {
  kind: string; parts: Part[]; captain: string;
  sys: number; world: World; ang: number; since: number;
  corp: number;                   // хозяин-компания; -1 если государственный
  gov: World | null;              // либо правительство мира
  lane: number;                   // дорожка на орбите, чтобы не слипались
}

// ---- рынок и патенты --------------------------------------------------

export interface MarketRow { price: number; last: number; want: number; stock: number; }
/** Биржа кораблей в одной системе, для одного типа корабля (ключ «система:тип»).
 *  k — во сколько раз корабль здесь дороже или дешевле стоимости его деталей;
 *  want — сколько раз за этот месяц здесь искали такой корабль;
 *  rate — сглаженный спрос, раз в год. */
export interface ShipRow { k: number; want: number; rate: number; }
export interface Patent { owner: number; since: number; told: boolean; }

/** Кеш на один тик. Живёт ровно один месяц симуляции, см. state.ts. */
export interface TickCache {
  wealth: Record<number, number>;              // богатство компании по её номеру
  prize: boolean | null;                       // остался ли "последний астероид"
  dev: Map<World, number>;                     // уровень освоения мира
  sellers: Record<string, Corp[]> | null;      // у кого есть эта деталь
  devBest: Record<number, Record<string, number>> | null;   // лучшая марка освоения: компания -> класс
}

/** Куда можно ткнуть на текущем кадре. Собирается заново каждой отрисовкой.
 *
 *  data нарочно широкое: под одним кругом на экране может оказаться планета,
 *  корабль, рейс, стоянка или предприятие, и разбирается это по kind. Сузить
 *  до объединения можно, но тогда каждое обращение к data потребует проверки
 *  kind ещё раз — ту самую, которую панель уже сделала.
 */
/** Что сейчас выбрано игроком: планета, корабль, рейс, стоянка, предприятие.
 *  Названо Chosen, а не Pick: Pick — встроенный служебный тип TypeScript, и
 *  своё определение с таким именем он молча перекрывает (см. журнал, п. 9). */
export interface Chosen { kind: string; data: any; }

/** То же, но с кругом на экране: чем именно попадают мышью. */
export interface Hit extends Chosen { x: number; y: number; r: number; }

/** Снимок партии, который ядро отдаёт наружу: стенду и тестам.
 *
 *  Это ДОГОВОР с test/, а не внутренняя структура. Поле, убранное отсюда,
 *  ломает тесты при сборке — так и задумано: раньше они узнавали об этом
 *  падением на середине прогона.
 */
export interface Snapshot {
  tick: number; treasury: number;
  corps: Corp[]; worlds: World[]; systems: Sys[];
  move: Move; gates: Record<string, Gate>;
  market: Record<string, MarketRow>; patents: Record<string, Patent>;
  /** Биржа кораблей: множитель к стоимости деталей по «система:тип». */
  shipMarket: Record<string, ShipRow>;
  /** Купленные детали, которые ждут корабль на погрузке. */
  freight: Lot[];
  voyages: Voyage[]; projects: Project[]; docks: Dock[];
  shipyards: Shipyard[]; proposals: Proposal[]; staged: Staged[];
  /** Война: корабли, бои в космосе и наземные битвы. */
  warships: Warship[]; fights: Fight[]; grounds: Ground[];
  /** Чертежи, до которых партия доросла. */
  designs: Design[];
  /** Военный фонд: что генерал не успел потратить. */
  armyFund: number;
  /** Боёв начато, кораблей сбито, восстаний поднято. */
  battles: number; downed: number; risings: number;
  /** Казна каждого отделившегося государства; родная лежит в treasury. */
  purses: Record<number, number>;
  /** Налог, который родная казна недополучила с отделившихся: ноль, пока их нет. */
  taxAway: number;
  trades: number; shipped: number; movedPops: number; refusals: number;
  dropped: number; hauled: number; burned: number; raids: number; lost: number;
  /** Карт продано и отказов в карте: по этим двум видно, держат ли конторы
   *  свои открытия при себе. */
  maps: number; mapNo: number;
  feed: { d: string; t: string }[];
}

/** Ядро, каким его видит стенд и тесты: см. src/main.ts.
 *
 *  Всё, что экспортирует main.ts, становится полем THRESHOLD в собранном
 *  файле. Этот интерфейс — тот же список, записанный один раз, чтобы тесты
 *  спорили с компилятором, а не с прогоном на трёхстах годах.
 */
export interface Core {
  step(): void;
  build(forcedMove?: string, seed?: number): void;
  /** Сид текущей партии: по нему она разворачивается заново. */
  seedOf(): number;
  state(): Snapshot;
  setLever(k: string, v: number | string): void;
  icon(ctx: CanvasRenderingContext2D, kind: string, x: number, y: number, s: number, col: string): void;
  consts: {
    COMPS: Comp[]; COLTECH: ColTech[]; PTYPES: PType[];
    VTYPES: VType[]; MOVES: Move[]; ENGINES: Engine[]; MARKS: Mark[]; BTYPES: BType[];
    /** Дальности ступеней — одни на марки перехода и на телескопы; сколько
     *  месяцев спутник ищет одну звезду; скольким конторам надо знать систему,
     *  чтобы её увидело государство. */
    MARKRANGE: number[]; SCAN_MONTHS: number; STATE_EYES: number;
    /** Военные детали: пять семейств по пять ступеней. */
    ARMS: Comp[];
    /** Чертежи, рождённые этой партией. Список живой: он растёт по ходу игры. */
    DESIGNS: Design[];
  };
  /** Знает ли контора эту систему (карты частные, charts.ts). */
  knowsSys(c: Corp, id: number): boolean;
  /** Видит ли систему государство: её знают хотя бы три конторы. */
  seenByState(id: number): boolean;
  speedOf(corpId: number): number;
  popOf(w: World): number;
  /** Урожай мира и выработка одного полевого фермера. Наружу выведены затем,
   *  что до сих пор продовольственные проверки могли только верить панели —
   *  а панель уже врала этим самым числом. */
  harvestOf(w: World): number;
  yieldPerFarmer(w: World): number;
  setView(mode: string, sys?: number): void;
  /** Как отвечать на предложения без игрока: стенду нужна политика. */
  setApproval(mode: ApproveMode): void;
  /** Решить судьбу предложения по его id; false — такого нет. */
  decide(id: number, ok: boolean): boolean;
  /** Партия целиком строкой — то же, что ложится в localStorage. */
  save(): string;
  /** Развернуть партию из строки; несовместимая бросает СОХРАНЕНИЕ НЕСОВМЕСТИМО. */
  load(text: string): void;
  /** Камера карты после последнего кадра. Карта сама держит в кадре известное
   *  (render/scene.ts, camFit), и прежнее «точка экрана — это точка карты»
   *  больше не верно: клик по карте стенд переводит через неё. */
  camera(): { x: number; y: number; k: number; free: boolean };
}
